import { useCallback, useMemo, useState } from 'react';
import { Activity, Search } from 'lucide-react';
import { getLogs } from '../api/client.js';
import ActivityTable from '../components/ActivityTable.jsx';
import PageHeader from '../components/PageHeader.jsx';
import ResourceState from '../components/ResourceState.jsx';
import StatusBadge from '../components/StatusBadge.jsx';
import useApiResource from '../hooks/useApiResource.js';

export default function ActivityLogsPage() {
  const [query, setQuery] = useState('');
  const [status, setStatus] = useState('All events');
  const loadLogs = useCallback(getLogs, []);
  const resource = useApiResource(loadLogs);
  const logs = resource.data?.items ?? [];
  const filteredLogs = useMemo(() => logs.filter((log) => {
    const matchesQuery = `${log.event} ${log.description} ${log.logical_clock ?? ''} ${log.node_id ?? ''}`
      .toLowerCase()
      .includes(query.trim().toLowerCase());
    const matchesStatus = status === 'All events' || log.status === status;
    return matchesQuery && matchesStatus;
  }), [logs, query, status]);

  return (
    <>
      <PageHeader
        eyebrow="OBSERVABILITY"
        title="Activity logs"
        description="Review activity events returned by the ClusterDrive API."
        action={<StatusBadge tone="blue">API event stream</StatusBadge>}
      />
      <ResourceState loading={resource.loading} error={resource.error} onRetry={resource.retry} label="Loading activity logs…">
        {resource.data && (
          <>
            <section className="log-summary-grid">
              <article className="panel log-summary-card"><span className="log-summary-icon icon-blue"><Activity size={17} /></span><span><small>Events returned</small><strong>{resource.data.count}</strong></span></article>
              <article className="panel log-summary-card"><span className="log-summary-icon icon-green"><i className="health-dot dot-green" /></span><span><small>Successful</small><strong>{logs.filter((item) => item.status === 'success').length}</strong></span></article>
              <article className="panel log-summary-card"><span className="log-summary-icon icon-amber"><i className="health-dot dot-amber" /></span><span><small>Warnings</small><strong>{logs.filter((item) => item.status === 'warning').length}</strong></span></article>
            </section>
            <section className="panel activity-page-panel">
              <div className="panel-heading">
                <div><p className="eyebrow">EVENT STREAM</p><h2>Recent events</h2></div>
                <div className="log-controls">
                  <label className="search-box log-search">
                    <Search size={16} aria-hidden="true" />
                    <input
                      type="search"
                      placeholder="Search activity"
                      value={query}
                      aria-label="Search activity"
                      onChange={(event) => setQuery(event.target.value)}
                    />
                  </label>
                  <select aria-label="Filter activity by status" value={status} onChange={(event) => setStatus(event.target.value)}>
                    <option>All events</option>
                    <option value="success">Success</option>
                    <option value="warning">Warning</option>
                    <option value="error">Error</option>
                    <option value="info">Info</option>
                  </select>
                </div>
              </div>
              <ActivityTable activities={filteredLogs} emptyMessage={logs.length === 0
                ? 'The API currently has no activity events.'
                : 'No events match the current search and filters.'}
              emptyDescription={logs.length === 0
                ? 'New events will appear here when backend services record them.'
                : 'Adjust the filters or search for another term.'}
              />
              <div className="file-panel-footer">
                <span>Showing {filteredLogs.length} of {resource.data.count} API events</span>
                <span>Event records are not generated by the frontend.</span>
              </div>
            </section>
            <div className="log-clock-note">
              <Activity size={16} />
              <p><strong>Logical clocks (Lamport clocks)</strong> are per-metadata-node counters used to reason about event order. Events include the node ID and logical timestamp when available; these counters do not represent real-world time.</p>
            </div>
          </>
        )}
      </ResourceState>
    </>
  );
}
